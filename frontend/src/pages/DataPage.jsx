import { AlertTriangle, Check, Download, FileJson2, FolderOpen, RefreshCw, Upload } from "lucide-react";
import { useRef, useState } from "react";
import { api } from "../services/api";
import { useApp } from "../context/AppContext";
import { DataTable, Button, Card, EmptyState, ErrorNotice, MetricCard, PageHeader, StatusBadge } from "../components/UI";
import { number } from "../utils/format";
import { parseDemandCsv } from "../utils/datasetUpload";

const DATA_KEYS = [
  "as_of",
  "synthetic",
  "seed",
  "demand_history",
  "inventory_batches",
  "lanes",
  "transport_costs",
  "capacities",
  "sku_min_shelf_life_days",
  "warehouse_receipts",
];
const PLANNING_TABLES = [
  "inventory_batches",
  "lanes",
  "transport_costs",
  "capacities",
  "sku_min_shelf_life_days",
  "warehouse_receipts",
];

function payloadForValidation(data, validationScope = "full_network") {
  return {
    ...Object.fromEntries(DATA_KEYS.filter((key) => key in data).map((key) => [key, data[key]])),
    validation_scope: validationScope,
  };
}

function downloadJson(data, filename) {
  const blob = new Blob([`${JSON.stringify(data, null, 2)}\n`], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}

export default function DataPage() {
  const { demoData, setDemoData, forecast, setForecast, rememberRun, notify } = useApp();
  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const fileRef = useRef(null);

  async function runForecast(data) {
    const result = await api.forecast({
      demand_history: data.demand_history,
      origin: data.as_of,
      horizon_days: 7,
      synthetic: Boolean(data.synthetic),
      seed: data.seed,
    });
    setForecast(result);
    rememberRun({ ...result, operation: "forecast" });
    return result;
  }

  async function validate(data = demoData, {
    forecastAfterValidation = false,
    validationScope,
  } = {}) {
    if (!data) return;
    const scope = validationScope || (
      PLANNING_TABLES.some((key) => key in data) ? "full_network" : "demand_only"
    );
    setLoading(true);
    setError(null);
    try {
      const result = await api.validateData(payloadForValidation(data, scope));
      setReport(result);
      if (result.valid && forecastAfterValidation) {
        const forecastResult = await runForecast(data);
        notify(`Dataset validated and ${forecastResult.forecasts.length} forecast rows generated by ${forecastResult.model_name}.`, "success");
      } else {
        notify(result.valid ? "Dataset validation completed without blocking errors." : "Validation completed with blocking findings.", result.valid ? "success" : "error");
      }
    } catch (caught) {
      setError(caught);
      if (caught.runId) rememberRun({ run_id: caught.runId, operation: "forecast", status: "failed" });
      notify(caught.message, "error");
    } finally {
      setLoading(false);
    }
  }

  async function loadDemo() {
    setLoading(true);
    setError(null);
    setForecast(null);
    try {
      const result = await api.getDemoData({ seed: 71, profile: "compact" });
      setDemoData(result);
      await validate(result, { forecastAfterValidation: true });
    } catch (caught) {
      setError(caught);
      setLoading(false);
    }
  }

  async function downloadDemo() {
    setLoading(true);
    setError(null);
    try {
      const dataset = await api.getDemoData({ seed: 71, profile: "compact" });
      downloadJson(dataset, "optiqo-demo-dataset.json");
      notify("Backend-generated demo dataset downloaded.", "success");
    } catch (caught) {
      setError(caught);
      notify(caught.message, "error");
    } finally {
      setLoading(false);
    }
  }

  async function openDataset(event) {
    const file = event.target.files?.[0];
    event.target.value = "";
    if (!file) return;
    if (file.size > 10 * 1024 * 1024) {
      setError(new Error("Dataset files are limited to 10 MiB in the frontend."));
      return;
    }

    setLoading(true);
    setError(null);
    setForecast(null);
    setReport(null);
    try {
      let dataset;
      if (file.name.toLowerCase().endsWith(".csv")) {
        dataset = { demand_history: parseDemandCsv(await file.text()), synthetic: false, profile: "uploaded CSV" };
        setDemoData(dataset);
        await validate(dataset, {
          validationScope: "demand_only",
          forecastAfterValidation: true,
        });
        return;
      }

      if (!file.name.toLowerCase().endsWith(".json")) {
        throw new Error("Choose a JSON dataset or a demand-history CSV file.");
      }
      const parsed = JSON.parse(await file.text());
      if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
        throw new Error("The JSON root must be an object containing demand_history.");
      }
      if (!Array.isArray(parsed.demand_history) || parsed.demand_history.length === 0) {
        throw new Error("Required dataset table 'demand_history' is missing or invalid.");
      }
      dataset = { ...parsed, synthetic: Boolean(parsed.synthetic), profile: parsed.profile || "uploaded JSON" };
      setDemoData(dataset);
      setReport(null);
      const includesPlanningData = PLANNING_TABLES.some((key) => key in dataset);
      if (includesPlanningData) {
        await validate(dataset, { forecastAfterValidation: true });
      } else {
        await validate(dataset, {
          validationScope: "demand_only",
          forecastAfterValidation: true,
        });
      }
    } catch (caught) {
      const error = caught instanceof SyntaxError
        ? new Error("The selected file contains invalid JSON.")
        : caught;
      setError(error);
      if (caught.runId) rememberRun({ run_id: caught.runId, operation: "forecast", status: "failed" });
      notify(error.message, "error");
    } finally {
      setLoading(false);
    }
  }

  const findings = report?.findings || [];
  const columns = [
    { key: "severity", label: "Severity", render: (value) => <StatusBadge status={value} /> },
    { key: "table", label: "Table" },
    { key: "row", label: "Row", render: (value) => value == null ? "—" : value + 1 },
    { key: "field", label: "Field" },
    { key: "rule", label: "Rule" },
    { key: "message", label: "Finding" },
  ];
  const forecastColumns = [
    { key: "forecast_date", label: "Forecast date" },
    { key: "sku_id", label: "Product" },
    { key: "destination_id", label: "Destination" },
    { key: "point_forecast", label: "Predicted demand", render: (value) => number(value, 2) },
  ];

  return (
    <div className="page-stack">
      <PageHeader eyebrow="Data quality" title="Data validation" description="Inspect structure and business constraints before forecasting or allocation." actions={<>
        <input ref={fileRef} className="visually-hidden" type="file" accept=".json,.csv,application/json,text/csv" onChange={openDataset} />
        <Button variant="outline" icon={Download} onClick={downloadDemo} disabled={loading}>Download demo JSON</Button>
        <Button variant="outline" icon={Upload} onClick={() => fileRef.current?.click()} disabled={loading}>Upload dataset</Button>
        <Button icon={FolderOpen} onClick={loadDemo} disabled={loading}>{loading ? "Processing…" : "Load demo data"}</Button>
      </>} />
      <div className="notice notice-info"><FileJson2 size={17} /><span>Upload a JSON dataset with demand_history (and the other engine tables for full validation), or a CSV demand-history file with columns sku_id, destination_id, demand_date, quantity. Forecasts are calculated by the backend engine. Upload limit: 10 MiB.</span></div>
      <ErrorNotice error={error} onRetry={() => validate()} />
      {demoData && <div className="transparency-strip"><span className="transparency-dot" /><strong>{demoData.synthetic ? "SYNTHETIC DATA" : "USER-SUPPLIED DATA"}</strong><span>{demoData.synthetic ? `Seed ${demoData.seed ?? "not provided"} · ${demoData.profile || "uploaded"} profile` : "Data provenance is supplied by the user and cannot be verified by the backend."}</span></div>}

      {demoData && <div className="metric-grid metric-grid-three">
        <MetricCard label="Demand rows" value={number(demoData.demand_history?.length, 0)} detail="SKU × destination × date records" icon={FileJson2} tone="blue" />
        <MetricCard label="Inventory batches" value={demoData.inventory_batches ? number(demoData.inventory_batches.length, 0) : "Not supplied"} detail={`${number(demoData.warehouse_receipts?.length, 0)} scheduled receipt rows`} icon={FolderOpen} tone="teal" />
        <MetricCard label="Eligible lane rows" value={demoData.lanes ? number(demoData.lanes.length, 0) : "Not supplied"} detail={`${number(demoData.capacities?.length, 0)} capacity records`} icon={Check} tone="violet" />
      </div>}

      {forecast && <Card title="Backend forecast" subtitle={`${forecast.forecasts.length} predictions · ${forecast.model_name}${forecast.fallback_used ? " · engine fallback" : ""}${forecast.run_id ? ` · run ${forecast.run_id.slice(0, 8)}` : ""}`}>
        <DataTable columns={forecastColumns} rows={forecast.forecasts} rowKey={(row) => `${row.forecast_date}-${row.sku_id}-${row.destination_id}`} />
      </Card>}

      {report && <Card title="Validation result" subtitle="Report returned by the FastAPI data validation route" action={<StatusBadge status={report.valid ? "valid" : "invalid"} />}>
        <div className="validation-summary">
          <div className={`validation-state ${report.valid ? "validation-ok" : "validation-fail"}`}>{report.valid ? <Check size={18} /> : <AlertTriangle size={18} />}<span><strong>{report.valid ? "No blocking errors" : "Blocking findings detected"}</strong><small>Warnings do not invalidate the report.</small></span></div>
          <div className="validation-count"><strong>{report.error_count}</strong><span>Errors</span></div>
          <div className="validation-count"><strong>{report.warning_count}</strong><span>Warnings</span></div>
        </div>
        <div className="table-scroll"><table className="data-table compact-table"><thead><tr><th>Table</th><th>Rows</th><th>Result</th></tr></thead><tbody>{Object.entries(report.tables || {}).map(([name, table]) => <tr key={name}><td>{name}</td><td>{number(table.row_count, 0)}</td><td><StatusBadge status={table.valid ? "valid" : "invalid"} /></td></tr>)}</tbody></table></div>
      </Card>}

      <Card title="Row-level findings" subtitle={`${findings.length} finding${findings.length === 1 ? "" : "s"} from the backend quality report`}>
        {findings.length ? <DataTable columns={columns} rows={findings} rowKey={(row) => `${row.table}-${row.row}-${row.rule}-${row.field}`} /> : <EmptyState title={report ? "No findings returned" : "No validation report"} description={report ? "The backend reported no errors or warnings for this dataset." : "Uploaded demand history can be validated independently. Full network validation requires a complete JSON dataset."} action={demoData && !report && <Button variant="outline" icon={RefreshCw} onClick={() => validate(demoData, { validationScope: PLANNING_TABLES.some((key) => key in demoData) ? "full_network" : "demand_only" })} disabled={loading}>Validate dataset</Button>} />}
      </Card>
    </div>
  );
}
