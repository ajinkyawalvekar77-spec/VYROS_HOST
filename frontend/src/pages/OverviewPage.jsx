import {
  Activity,
  ArrowRight,
  Boxes,
  CircleAlert,
  ClipboardCheck,
  PackageSearch,
  Sparkles,
  Truck,
} from "lucide-react";
import { useState } from "react";
import { Link } from "react-router-dom";
import {
  Area,
  AreaChart,
  CartesianGrid,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";
import { api } from "../services/api";
import { useApp } from "../context/AppContext";
import { number, percent, shortId, total } from "../utils/format";
import { Button, Card, EmptyState, ErrorNotice, LoadingState, MetricCard, PageHeader, RunLink, StatusBadge } from "../components/UI";

function historicalTrend(rows = []) {
  const byDay = new Map();
  rows.forEach((row) => {
    const date = String(row.demand_date).slice(0, 10);
    byDay.set(date, (byDay.get(date) || 0) + Number(row.quantity || 0));
  });
  return [...byDay.entries()]
    .slice(-28)
    .map(([date, demand]) => ({ date: date.slice(5), demand: Math.round(demand) }));
}

export default function OverviewPage() {
  const {
    demoData,
    setDemoData,
    forecast,
    setForecast,
    plan,
    runs,
    rememberRun,
    notify,
  } = useApp();
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);

  async function loadDemo() {
    setLoading(true);
    setError(null);
    try {
      const dataset = await api.getDemoData({ seed: 71, profile: "compact" });
      setDemoData(dataset);
      const result = await api.forecast({
        demand_history: dataset.demand_history,
        origin: dataset.as_of,
        horizon_days: 7,
        synthetic: true,
        seed: dataset.seed,
      });
      setForecast(result);
      rememberRun({ ...result, operation: "forecast" });
      notify("Synthetic dataset loaded and forecast completed.", "success");
    } catch (caught) {
      setError(caught);
      if (caught.runId) rememberRun({ run_id: caught.runId, operation: "forecast", status: "failed" });
      notify(caught.message, "error");
    } finally {
      setLoading(false);
    }
  }

  const historicalTotal = total(demoData?.demand_history, "quantity");
  const forecastTotal = total(forecast?.forecasts, "point_forecast");
  const trend = historicalTrend(demoData?.demand_history);
  const latestRuns = runs.slice(0, 4);

  return (
    <div className="page-stack">
      <PageHeader
        eyebrow="Network intelligence"
        title="Overview"
        description="A grounded view of demand, supply, and distribution decisions."
        actions={<Button icon={Sparkles} onClick={loadDemo} disabled={loading}>{loading ? "Connecting…" : demoData ? "Refresh synthetic data" : "Load synthetic demo"}</Button>}
      />
      <div className="transparency-strip">
        <span className="transparency-dot" />
        <strong>{demoData ? "SYNTHETIC DATA" : "NO DATA LOADED"}</strong>
        <span>{demoData ? `Seed ${demoData.seed} · ${demoData.profile} profile · generated by the Optiqo backend` : "Load the backend-generated demo dataset to explore live model outputs."}</span>
      </div>
      <ErrorNotice error={error} onRetry={loadDemo} />

      {!demoData && !loading ? (
        <Card className="overview-welcome">
          <div className="welcome-icon"><Boxes size={24} /></div>
          <div><span className="eyebrow">Your decision workspace</span><h2>Start with real engine outputs.</h2><p>Load the backend’s reproducible synthetic dataset to validate inputs and request a genuine forecast. No sample KPI values are pre-filled.</p></div>
          <Button icon={ArrowRight} onClick={loadDemo}>Load demo dataset</Button>
        </Card>
      ) : loading && !demoData ? <LoadingState label="Loading backend dataset and running the forecast…" /> : (
        <>
          <div className="metric-grid">
            <MetricCard label="Historical demand" value={demoData ? `${number(historicalTotal, 0)} units` : "Unavailable"} detail={demoData ? `${demoData.demand_history.length.toLocaleString()} daily observations` : "Load a dataset"} icon={Activity} tone="blue" />
            <MetricCard label="7-day forecast" value={forecast ? `${number(forecastTotal, 0)} units` : "Unavailable"} detail={forecast ? `${forecast.model_name}${forecast.fallback_used ? " · fallback" : ""}` : "Forecast not run"} icon={Sparkles} tone="violet" />
            <MetricCard label="Warehouse stock" value={demoData ? `${number(total(demoData.inventory_batches, "quantity"), 0)} units` : "Unavailable"} detail={demoData ? `${demoData.inventory_batches.length} batch records` : "No inventory loaded"} icon={PackageSearch} tone="teal" />
            <MetricCard label="Verified plan" value={plan?.verification?.is_valid ? "Verified" : "Not generated"} detail={plan?.solver?.status || "No solver result"} icon={ClipboardCheck} tone={plan?.verification?.is_valid ? "green" : "amber"} />
          </div>

          <div className="content-grid content-grid-main">
            <Card title="Demand history" subtitle="Daily synthetic demand · network total · units" action={<StatusBadge status="Synthetic">Backend-generated</StatusBadge>}>
              {trend.length ? (
                <div className="chart-wrap chart-overview">
                  <ResponsiveContainer width="100%" height="100%">
                    <AreaChart data={trend} margin={{ top: 10, right: 10, left: 0, bottom: 0 }}>
                      <defs><linearGradient id="demandFill" x1="0" x2="0" y1="0" y2="1"><stop offset="0%" stopColor="#5577ed" stopOpacity={0.24} /><stop offset="100%" stopColor="#5577ed" stopOpacity={0} /></linearGradient></defs>
                      <CartesianGrid strokeDasharray="3 5" vertical={false} />
                      <XAxis dataKey="date" tickLine={false} axisLine={false} />
                      <YAxis tickLine={false} axisLine={false} width={42} />
                      <Tooltip formatter={(value) => [`${number(value, 0)} units`, "Historical demand"]} />
                      <Area type="monotone" dataKey="demand" stroke="#5577ed" strokeWidth={2.4} fill="url(#demandFill)" />
                    </AreaChart>
                  </ResponsiveContainer>
                </div>
              ) : <EmptyState title="No demand history" description="Load the backend demo dataset to view historical demand." />}
            </Card>
            <Card title="Planning status" subtitle="Current workflow outputs">
              <div className="status-list">
                <div><span className="status-icon status-icon-blue"><Sparkles size={15} /></span><span><strong>Forecast</strong><small>{forecast ? `${forecast.forecasts.length} forecast rows from ${forecast.model_name}` : "No forecast run recorded"}</small></span><StatusBadge status={forecast ? "succeeded" : "not run"} /></div>
                <div><span className="status-icon status-icon-green"><Truck size={15} /></span><span><strong>Allocation</strong><small>{plan ? `${plan.plan.length} plan lines` : "No plan generated"}</small></span><StatusBadge status={plan?.verification?.is_valid ? "verified" : plan ? plan.solver.status : "not run"} /></div>
                <div><span className="status-icon status-icon-amber"><CircleAlert size={15} /></span><span><strong>Risk</strong><small>Measured stock and forecast indicators</small></span><Link className="small-link" to="/app/risk">Open <ArrowRight size={13} /></Link></div>
              </div>
              <div className="card-footer-action"><Link to="/app/plan">Open distribution planning <ArrowRight size={14} /></Link></div>
            </Card>
          </div>

          <div className="content-grid content-grid-secondary">
            <Card title="Recent runs" subtitle="Runs initiated from this browser">
              {latestRuns.length ? <div className="run-list">{latestRuns.map((run) => <RunLink key={run.run_id} run={run} />)}<Link to="/app/runs" className="view-all-link">View run history <ArrowRight size={14} /></Link></div> : <EmptyState title="No run history yet" description="Forecast, validate, plan, or run a backtest to create backend run records." action={<Link className="small-link" to="/app/data">Start with data validation <ArrowRight size={14} /></Link>} />}
            </Card>
            <Card title="Connected workflow" subtitle="Backend and engine operations">
              <div className="workflow-status">
                <div><span className="workflow-status-icon"><Activity size={16} /></span><span><strong>Forecast engine</strong><small>{forecast ? `${forecast.model_name}${forecast.fallback_used ? " fallback" : ""}` : "Waiting for a request"}</small></span></div>
                <div><span className="workflow-status-icon"><ClipboardCheck size={16} /></span><span><strong>Independent checker</strong><small>{plan ? plan.verification.summary : "Runs with allocation plans"}</small></span></div>
                <div><span className="workflow-status-icon"><Boxes size={16} /></span><span><strong>Recent run reference</strong><small className="mono">{runs[0]?.run_id ? shortId(runs[0].run_id) : "None"}</small></span></div>
              </div>
            </Card>
          </div>
          {forecast?.fallback_used && <div className="notice notice-warning"><CircleAlert size={17} /><span>Forecast fallback reported by engine: {forecast.fallback_reason || forecast.model_name}. The selected model is shown as returned by the backend.</span></div>}
        </>
      )}
    </div>
  );
}
